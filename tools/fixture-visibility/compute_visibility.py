#!/usr/bin/env python3
"""Computes fixtures/company.visibility.yaml, the RBAC test oracle, from fixtures/company.yaml.

This is a deliberately independent re-implementation of the access rules in CLAUDE.md (it does not share code
with the server's AccessEvaluator), so the two can be compared:

  * a user can read an item when one of the item's effective grants names the user, a group the user belongs to
    (directly or through nested groups) or a site group whose members include the user or one of those groups;
  * effective grants of an item are its own grants plus those of its ancestors, up to and including the nearest
    ancestor (or the item itself) with breakInheritance: true; any role (read, write, owner) implies read;
  * folders and files are listed separately; `app` can read everything.

Usage:  python tools/fixture-visibility/compute_visibility.py [--check]
Needs PyYAML. With --check the file is not written; the exit code is 1 when it would change.
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "fixtures" / "company.yaml"
TARGET = ROOT / "fixtures" / "company.visibility.yaml"


def norm(path):
    return "/" + path.strip().strip("/")


def parent(path):
    return path.rsplit("/", 1)[0] or "/"


def main():
    fixture = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    users = [u["id"] for u in fixture["users"]]
    groups = {g["id"]: list(g.get("members", [])) for g in fixture["groups"]}

    def closure(user):
        """All group ids the user belongs to, directly or through nesting."""
        reached = {f"user:{user}"}
        changed = True
        while changed:
            changed = False
            for gid, members in groups.items():
                if f"group:{gid}" not in reached and any(m in reached for m in members):
                    reached.add(f"group:{gid}")
                    changed = True
        return reached

    site_groups = {}
    for site in fixture["sites"]:
        for sg in site.get("siteGroups", []):
            site_groups[sg["id"]] = list(sg.get("members", []))

    principals = {}
    for user in users:
        reached = closure(user)
        for sgid, members in site_groups.items():
            if any(m in reached for m in members):
                reached.add(f"siteGroup:{sgid}")
        principals[user] = reached

    result = {u: {"files": [], "folders": []} for u in users}
    result["app"] = {"files": [], "folders": []}
    drive_ids = []
    for site in fixture["sites"]:
        for drive in site["drives"]:
            drive_ids.append(drive["id"])
            items = {}
            for it in drive["items"]:
                p = norm(it["path"])
                items[p.lower()] = {
                    "path": p,
                    "folder": "content" not in it and "source" not in it and "contentBase64" not in it,
                    "break": bool(it.get("breakInheritance")),
                    "grants": [g["principal"] for g in it.get("permissions", [])],
                }
            for entry in list(items.values()):
                # Folders that the fixture does not list are created implicitly, with no grants of their own.
                implicit = parent(entry["path"])
                while implicit != "/":
                    if implicit.lower() not in items:
                        items[implicit.lower()] = {"path": implicit, "folder": True, "break": False, "grants": []}
                    implicit = parent(implicit)

            for key, it in items.items():
                effective, cursor = [], key
                while cursor != "/":
                    node = items[cursor]
                    effective += node["grants"]
                    if node["break"]:
                        break
                    cursor = parent(cursor)
                label = f"{drive['id']}:{it['path']}"
                bucket = "folders" if it["folder"] else "files"
                result["app"][bucket].append(label)
                for user in users:
                    if any(g in principals[user] for g in effective):
                        result[user][bucket].append(label)

    out = {"users": {}}
    for user in users:
        out["users"][user] = {
            "groups": sorted(g[len("group:"):] for g in closure(user) if g.startswith("group:")),
            "files": sorted(result[user]["files"]),
            "folders": sorted(result[user]["folders"]),
        }
    out["app"] = {"files": sorted(result["app"]["files"]), "folders": sorted(result["app"]["folders"])}

    header = (
        "# Expected visibility for fixtures/company.yaml: the RBAC test oracle.\n"
        "# GENERATED by tools/fixture-visibility/compute_visibility.py. Do not edit by hand; re-run the script after changing the fixture.\n"
        "# Entries are <driveId>:<drive-relative path>, sorted by ordinal (code point) order.\n"
        "# `files` and `folders` are everything the user can read, whether or not a parent folder is listable:\n"
        "# a readable item under an unreadable folder is NOT reachable by walking from the root, but it can be opened by id.\n"
        "# `groups` are the user's groups including nested ones (what /users/{id}/transitiveMemberOf returns).\n"
        "# `app` (app-only token) reads everything.\n"
    )
    text = header + yaml.safe_dump(out, allow_unicode=True, sort_keys=False, width=1000, default_flow_style=False)
    if "--check" in sys.argv:
        return 0 if TARGET.exists() and TARGET.read_text(encoding="utf-8") == text else 1
    TARGET.write_text(text, encoding="utf-8")
    for user in users:
        print(f"{user:7s} files={len(out['users'][user]['files']):3d} folders={len(out['users'][user]['folders']):3d}")
    print(f"app     files={len(out['app']['files'])} folders={len(out['app']['folders'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
